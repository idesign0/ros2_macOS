#!/usr/bin/env python3
"""
Generate Homebrew formulae for a split ROS 2 macOS distribution.

One formula per domain plus a base formula and a metaformula, all in ONE tap so the
whole set updates in a single atomic commit.

Nothing here is hand-maintained. For each tree it derives:
  * the packages it provides      -> share/ament_index/resource_index/packages/
  * cross-domain dependencies     -> .../package_run_dependencies/<pkg>, mapped through
                                     the provider index built from every tree
  * Homebrew dependencies         -> otool -L on its dylibs, /opt/homebrew/opt/<f>/...
so the formula graph cannot drift from what was actually built.

Usage:
  genformulae.py --version 26.10.29 --distro kilted \
                 --base <dir>  --domain <name>=<dir> [--domain ...] \
                 --url-prefix <url-or-file://...>  --out <dir>
"""
import argparse, hashlib, json, os, pathlib, re, subprocess, sys
from collections import defaultdict

HB = "/opt/homebrew"
AI = "share/ament_index/resource_index"


def provides(tree):
    d = pathlib.Path(tree) / AI / "packages"
    return set(os.listdir(d)) if d.is_dir() else set()


def run_deps(tree):
    """package -> set(dependency names), from the ament index."""
    d = pathlib.Path(tree) / AI / "package_run_dependencies"
    out = {}
    if not d.is_dir():
        return out
    for f in d.iterdir():
        try:
            out[f.name] = {x for x in f.read_text().strip().split(";") if x}
        except OSError:
            pass
    return out


def brew_deps(tree):
    """Homebrew formulae this tree's mach-o files actually link against."""
    found = set()
    pat = re.compile(rf"^{re.escape(HB)}/opt/([^/]+)/")
    files = []
    for root, _, names in os.walk(pathlib.Path(tree) / "lib"):
        for n in names:
            if n.endswith((".dylib", ".so")):
                p = os.path.join(root, n)
                if not os.path.islink(p):
                    files.append(p)
    # one otool call per batch keeps this tractable on a 17k-file tree
    for i in range(0, len(files), 200):
        batch = files[i:i + 200]
        try:
            out = subprocess.run(["otool", "-L", *batch], capture_output=True,
                                 text=True, timeout=600).stdout
        except (subprocess.SubprocessError, OSError):
            continue
        for line in out.splitlines():
            m = pat.match(line.strip().split(" ")[0])
            if m:
                found.add(m.group(1))
    # keg-only aliases and versioned kegs resolve to their formula name as-is
    return found


def curated_deps(formula_path):
    """The hand-maintained depends_on list. otool finds only LINK-time deps; it misses
    dlopen'd plugins (ogre1.9/2.3 for gz rendering), python modules and data-only
    formulae (gts, gpsd) -- 26 of 61 were missing in the jazzy comparison. So the
    curated list is the baseline and otool is an auditor on top of it."""
    if not formula_path:
        return set()
    txt = pathlib.Path(formula_path).read_text()
    return set(re.findall(r'^\s*depends_on\s+"([^"]+)"', txt, re.M))


def sha256(path):
    h = hashlib.sha256()
    with open(path, "rb") as fh:
        for chunk in iter(lambda: fh.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def rb_class(name):
    return "".join(p.capitalize() for p in re.split(r"[-_@.]", name) if p)


def _unlink_note(unlinkable):
    if not unlinkable:
        return ""
    names = " ".join(unlinkable)
    return (f"      These dependencies may safely be unlinked -- this keg references them\n"
            f"      through #{{HOMEBREW_PREFIX}}/opt/<formula>, which `brew unlink` keeps:\n"
            f"        brew unlink {names}\n"
            f"      Unlinking them is what the CI build itself does, and it avoids them\n"
            f"      shadowing headers for anything else you compile.\n\n")


KEG_ONLY = (
    'it ships copies of files its own dependencies also provide, and ROS 2 is used '
    'by sourcing setup.zsh rather than by linking'
)

HEADER = '''# GENERATED by ci/deploy/genformulae.py -- do not edit by hand.
# Regenerate from the build artifacts; the dependency graph below is derived from the
# installed ament index and from otool -L, so it cannot drift from what was built.
'''


def formula(name, desc, version, url, sha, deps, snapshot, base_name=None,
            is_meta=False, packages=0, unlinkable=()):
    dep_lines = "\n".join(f'  depends_on "{d}"' for d in sorted(deps))
    if is_meta:
        body = f'''{HEADER}
class {rb_class(name)} < Formula
  desc "{desc}"
  homepage "https://github.com/idesign0/homebrew-ros2"
  version "{version}"
  # Metaformula: no payload of its own, it just pulls in the whole set.
  url "file:///dev/null"
  sha256 :no_check

{dep_lines}

  def install
    (prefix/"SNAPSHOT").write "{snapshot}\\n"
  end

  def caveats
    <<~EOS
      Full ROS 2 stack for this snapshot ({snapshot}).
      Source it with:
        source #{{Formula["{base_name}"].opt_prefix}}/setup.zsh
      then each domain overlay, or use the generated ros2-{{distro}}-env script.
    EOS
  end
end
'''
        return body

    snap_guard = ""
    if base_name:
        snap_guard = f'''
    # Mixed-snapshot guard. A domain's dylibs embed base's opt path and expect the
    # symbols of the base it was built against; ROS 2 has no ABI stability between
    # snapshots. Turn that into one clear install-time error instead of a
    # "Library not loaded" weeks later.
    base_snap = Formula["{base_name}"].opt_prefix/"SNAPSHOT"
    if base_snap.exist? && base_snap.read.strip != "{snapshot}"
      odie <<~ERR
        Snapshot mismatch: this formula was built against base snapshot {snapshot},
        but the installed {base_name} is #{{base_snap.read.strip}}.
        Run `brew upgrade` so the whole set moves together, or pin the tap to a tag.
      ERR
    end
'''

    return f'''{HEADER}
class {rb_class(name)} < Formula
  desc "{desc}"
  homepage "https://github.com/idesign0/homebrew-ros2"
  version "{version}"
  url "{url}"
  sha256 "{sha}"

  # Deliberately NOT linked into HOMEBREW_PREFIX: the tree ships copies of programs and
  # headers that its own declared dependencies also provide (protoc, check_urdf,
  # binvox2bt, gz, GeographicLib/benchmark headers). Linking hands those shared names to
  # this keg; see idesign0/ros2_macOS#8. setup.zsh resolves its own location via
  # COLCON_CURRENT_PREFIX, so sourcing works with the keg unlinked.
  keg_only "{KEG_ONLY}"

{dep_lines}

  # {packages} ament packages in this tree.
  def install
    prefix.install Dir["*"]
    (prefix/"SNAPSHOT").write "{snapshot}\\n"
  end

  def post_install{snap_guard}
  end

  def caveats
    <<~EOS
{_unlink_note(unlinkable)}      Source this overlay AFTER base:
        source #{{Formula["{base_name or name}"].opt_prefix}}/setup.zsh
        COLCON_CURRENT_PREFIX=#{{opt_prefix}} source #{{opt_prefix}}/local_setup.zsh
    EOS
  end
end
'''


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--version", required=True)
    ap.add_argument("--distro", required=True)
    ap.add_argument("--base", required=True)
    ap.add_argument("--domain", action="append", default=[], metavar="NAME=DIR")
    ap.add_argument("--url-prefix", required=True)
    ap.add_argument("--out", required=True)
    ap.add_argument("--dist", required=True, help="dir holding the tarballs")
    ap.add_argument("--no-brew-deps", action="store_true",
                    help="skip the otool scan (fast, for structure-only runs)")
    ap.add_argument("--curated", help="existing formula to take the curated depends_on "
                                      "list from; otool is a FLOOR, not the whole set")
    ap.add_argument("--no-tarball", action="store_true",
                    help="emit formulae with a placeholder sha256 (graph verification)")
    ap.add_argument("--unlinkable", help="file of formulae the build unlinks; these are "
                                         "still declared (the opt path is what binaries "
                                         "reference) but are listed in caveats")
    a = ap.parse_args()

    trees = {"base": a.base}
    for d in a.domain:
        n, _, p = d.partition("=")
        trees[n] = p

    out = pathlib.Path(a.out)
    out.mkdir(parents=True, exist_ok=True)

    # provider index across every tree
    prov, pkgs = {}, {}
    for comp, tree in trees.items():
        pkgs[comp] = provides(tree)
        for p in pkgs[comp]:
            prov[p] = comp
        print(f"  {comp:<16} {len(pkgs[comp]):>4} packages", file=sys.stderr)

    # cross-component edges from the ament index
    edges = defaultdict(set)
    unresolved = defaultdict(set)
    for comp, tree in trees.items():
        for pkg, deps in run_deps(tree).items():
            for dep in deps:
                owner = prov.get(dep)
                if owner is None:
                    unresolved[comp].add(dep)
                elif owner != comp:
                    edges[comp].add(owner)

    curated = curated_deps(a.curated)
    unlinkable = (set(pathlib.Path(a.unlinkable).read_text().split())
                  if a.unlinkable else set())
    print(f"  curated deps: {len(curated)}   unlinkable: {len(unlinkable)}", file=sys.stderr)

    audit = {}
    written = []
    for comp, tree in trees.items():
        fname = f"ros2-{a.distro}" + ("" if comp == "base" else f"-{comp}")
        fname = f"ros2-{a.distro}-base" if comp == "base" else fname
        tar = pathlib.Path(a.dist) / f"{fname}-{a.version}.tar"
        if not tar.exists() and not a.no_tarball:
            print(f"  !! no tarball for {comp}: {tar}", file=sys.stderr)
            continue
        sha = "0" * 64 if a.no_tarball else sha256(tar)
        bd = set() if a.no_brew_deps else brew_deps(tree)
        cur = curated if comp == "base" else set()
        extra = bd - cur - curated            # linked but nobody declared it
        if extra:
            audit[comp] = sorted(extra)
        deps = {f"ros2-{a.distro}-{e}" if e != "base" else f"ros2-{a.distro}-base"
                for e in edges[comp]} | bd | cur
        deps.discard(fname)
        f = out / f"{fname}.rb"
        f.write_text(formula(
            fname,
            f"ROS 2 {a.distro.capitalize()} -- {'base layer' if comp=='base' else comp + ' domain'}",
            a.version, f"{a.url_prefix}/{tar.name}", sha, deps, a.version,
            base_name=None if comp == "base" else f"ros2-{a.distro}-base",
            packages=len(pkgs[comp]),
            unlinkable=sorted(deps & unlinkable)))
        written.append((fname, len(deps), len(pkgs[comp])))
        print(f"  wrote {f.name:<34} deps={len(deps):<3} ament_pkgs={len(pkgs[comp])}",
              file=sys.stderr)

    for comp, miss in unresolved.items():
        if miss:
            print(f"  note: {comp} has {len(miss)} deps provided by no tree "
                  f"(expected when only a subset is passed): "
                  f"{', '.join(sorted(miss)[:6])}...", file=sys.stderr)

    if audit:
        print("\n  AUDIT -- linked via otool but in NO curated list "
              "(declare them, or find out why they are linked):", file=sys.stderr)
        for comp, xs in sorted(audit.items()):
            print(f"    {comp:<16} {', '.join(xs)}", file=sys.stderr)

    print(json.dumps({"written": written, "audit": audit,
                      "edges": {k: sorted(v) for k, v in edges.items()}}, indent=2))


if __name__ == "__main__":
    main()
